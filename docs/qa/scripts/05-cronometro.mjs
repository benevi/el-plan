// Recorrido 5: series, kilos, descanso con alarma y vibración (espía), ±15, pantalla bloqueada y ejercicio por tiempo.
// Usa page.clock para avanzar el tiempo sin esperar de verdad.
import { navegador, contexto, vigilar, foto, leer, botones, esperar, empezar } from './comun.mjs';
const movil = process.argv[2] || 'm390';
const b = await navegador();
const ctx = await contexto(b, movil); const page = await ctx.newPage(); const err = vigilar(page);
await page.clock.install({ time: new Date('2026-11-21T10:00:00+01:00') });
await empezar(page, 'victor', { objetivos: ['musculo'] });
await page.click('#nav a[href="#hoy"]');
await page.click('[data-act="entrenador.plan"]');
for (const d of [6, 7]) await page.click(`[data-act="entrenador.psDia"][data-v="${d}"]`);
await page.click('[data-act="entrenador.crearPlan"][data-ia="0"]'); await page.clock.runFor(500);
await page.click('[data-act="entrenador.prepararHoy"]'); await page.clock.runFor(400);
await page.click('[data-act="entrenador.crearHoy"]'); await page.clock.runFor(800);
await page.click('[data-act="sesion.modo"][data-v="lista"]');
const vib = () => page.evaluate(() => window.__vib.splice(0));
// kilos y serie 1
await page.fill('[data-cambio="sesion.dato"][data-e="0"][data-s="0"][data-k="kg"]', '20,5');
await page.locator('[data-cambio="sesion.dato"][data-e="0"][data-s="0"][data-k="kg"]').blur();
await page.click('[data-act="sesion.serie"][data-e="0"][data-s="0"]'); await page.clock.runFor(300);
let L = await leer(page); console.log('crono tras serie 1:', JSON.stringify(L.crono));
const fila = await page.$eval('#ej-0 .serie', li => li.innerText.replace(/\n/g, ' '));
console.log('fila 1 tras marcar:', fila, '| guardado:', await page.evaluate(() => JSON.stringify(Object.values(JSON.parse(localStorage.pipos4).sesiones)[0].ejercicios[0].sets[0])));
await foto(page, `05-${movil}-descanso`);
await page.click('#temporizador [data-t="mas"]'); await page.clock.runFor(300);
console.log('tras +15:', (await leer(page)).crono);
await page.click('#temporizador [data-t="menos"]'); await page.click('#temporizador [data-t="menos"]'); await page.clock.runFor(300);
console.log('tras −15 −15:', (await leer(page)).crono);
await page.clock.runFor(103_000);
L = await leer(page); console.log('justo antes del final:', L.crono, '| alarma:', L.alarma);
await page.clock.runFor(3000);
L = await leer(page); console.log('al acabar:', 'crono', JSON.stringify(L.crono), '| alarma', JSON.stringify(L.alarma));
await foto(page, `05-${movil}-alarma-descanso`);
console.log('vibraciones al acabar:', JSON.stringify(await vib()));
await page.clock.runFor(31_000);
console.log('vibraciones 31 s después:', JSON.stringify(await vib()));
console.log('alarma sigue?', (await leer(page)).alarma);
await page.click('.alarma'); await page.clock.runFor(200);
console.log('tras tocar alarma:', JSON.stringify((await leer(page)).alarma), JSON.stringify(await vib()));
// Pantalla bloqueada durante el descanso
await page.click('[data-act="sesion.serie"][data-e="0"][data-s="1"]'); await page.clock.runFor(300);
console.log('descanso 2:', (await leer(page)).crono);
const oculto = v => page.evaluate(v => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => v }); Object.defineProperty(document, 'visibilityState', { configurable: true, get: () => v ? 'hidden' : 'visible' }); document.dispatchEvent(new Event('visibilitychange')); }, v);
await oculto(true);
await page.clock.runFor(150_000);
console.log('vibraciones con la pantalla bloqueada:', JSON.stringify(await vib()));
await oculto(false); await page.clock.runFor(300);
L = await leer(page); console.log('al volver:', JSON.stringify(L.alarma), JSON.stringify(L.crono));
await foto(page, `05-${movil}-alarma-al-volver`);
console.log('vibraciones al volver:', JSON.stringify(await vib()));
await page.click('.alarma').catch(() => {});
// Ejercicio por tiempo: el cardio (8 min)
const i = await page.evaluate(() => Object.values(JSON.parse(localStorage.pipos4).sesiones)[0].ejercicios.findIndex(x => x.rol === 'cardio'));
const filaC = await page.$eval(`#ej-${i} .serie`, li => li.innerHTML.replace(/<svg.*?<\/svg>/g, ''));
console.log('fila cardio:', filaC);
await page.click(`[data-act="sesion.cuenta"][data-e="${i}"][data-s="0"]`); await page.clock.runFor(300);
console.log('previa:', (await leer(page)).crono.replace(/\n/g, ' | '));
await foto(page, `05-${movil}-cuenta-previa`);
await page.clock.runFor(5000);
console.log('trabajo:', (await leer(page)).crono.replace(/\n/g, ' | '), JSON.stringify(await vib()));
await foto(page, `05-${movil}-cuenta-trabajo`);
await page.clock.runFor(60_000);
await page.click('#temporizador [data-t="pausa"]'); await page.clock.runFor(10_000);
console.log('en pausa 10 s:', (await leer(page)).crono.replace(/\n/g, ' | '));
await page.click('#temporizador [data-t="pausa"]'); await page.clock.runFor(420_000);
console.log('al llegar a 8 min:', (await leer(page)).crono.replace(/\n/g, ' | '), JSON.stringify(await vib()));
await foto(page, `05-${movil}-cuenta-superado`);
await page.click('#temporizador [data-t="fin"]'); await page.clock.runFor(500);
L = await leer(page);
console.log('tras Hecho:', JSON.stringify(L.crono), JSON.stringify(L.alarma), '| fila:', await page.$eval(`#ej-${i}`, e => e.innerText.replace(/\n/g, ' ')).catch(() => 'plegada'));
console.log('guardado cardio:', await page.evaluate(i => JSON.stringify(Object.values(JSON.parse(localStorage.pipos4).sesiones)[0].ejercicios[i].sets), i));
await foto(page, `05-${movil}-tras-cardio`);
console.log('errores', err);
await b.close();
