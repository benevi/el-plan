import { abrir, foto, BASE, texto } from './h.mjs';
import { sembrar, tTxt, sets, esconder } from './sembrar.mjs';
const { browser, page } = await abrir({ w: 360, hgt: 640 });
const id = await sembrar(page, 'victor', { modo: 'foco' });
await page.goto(BASE + '/#sesion/' + id); await page.waitForSelector('.vista-sesion');
const L = (...a) => console.log(...a);
await page.click('[data-act="sesion.ir"][data-v="4"]'); await page.clock.runFor(200);
L((await texto(page)).slice(0, 600));
await foto(page, '05-cardio-paso');
await page.click('[data-act="sesion.cuenta"]'); await page.clock.runFor(6000);
L('cardio 1 s', await tTxt(page));
await esconder(page, true); await page.clock.runFor(9 * 60000); await esconder(page, false); await page.clock.runFor(300);
L('al volver tras 9 min bloqueado', await tTxt(page));
await foto(page, '05-cardio-confirmar');
await page.click('#temporizador [data-t="apuntar"]'); await page.clock.runFor(300);
L('sets', JSON.stringify(await sets(page, id, 3)));
L((await texto(page)).slice(0, 500));
await foto(page, '05-cardio-tras');
await browser.close();
